/* Progressive enhancement. Navigation, confirmations and actions use server-rendered forms. */
(function () {
    'use strict';
    const root = document.querySelector('.fic-admin');
    if (!root) return;
    const controls = root.querySelector('[data-fic-filters]');
    const table = root.querySelector('[data-fic-queue]');
    if (controls && table) {
        const search = controls.querySelector('[data-fic-search]');
        const filter = controls.querySelector('[data-fic-filter]');
        const rows = Array.from(table.querySelectorAll('tbody tr[data-fic-state]'));
        const count = controls.querySelector('[data-fic-count]');
        const empty = root.querySelector('[data-fic-empty]');
        const apply = function () {
            const term = search.value.trim().toLocaleLowerCase('it');
            let visible = 0;
            rows.forEach(function (row) {
                const state = row.dataset.ficState;
                const match = filter.value === 'all' || state === filter.value ||
                    (filter.value === 'pending' && ['queued', 'waiting', 'processing'].includes(state)) ||
                    (filter.value === 'review' && !['queued', 'waiting', 'processing', 'created', 'linked'].includes(state));
                row.hidden = !match || !row.textContent.toLocaleLowerCase('it').includes(term);
                if (!row.hidden) visible++;
            });
            count.textContent = visible + ' di ' + rows.length + ' ordini nel campione';
            empty.hidden = visible > 0 || rows.length === 0;
        };
        // Do not present an unavailable queue as a zero-result search.
        if (rows.length) { controls.hidden = false; apply(); }
        search.addEventListener('input', apply);
        filter.addEventListener('change', apply);
    }
    // Tables generated by the existing manual and diagnostic tools may be wide.
    root.querySelectorAll('table.widefat').forEach(function (table) {
        if (table.closest('.fic-table-scroll')) return;
        const scroll = document.createElement('div');
        scroll.className = 'fic-table-scroll';
        table.before(scroll);
        scroll.append(table);
    });
}());
